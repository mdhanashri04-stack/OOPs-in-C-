// Include the input-output stream library
#include <iostream>

// Use the standard namespace
using namespace std;

// Main function
int main() {

    // Declare a variable to store marks
    int marks = 45;

    // Check whether marks are greater than or equal to 40
    if (marks >= 40) {

        // Display "Pass" if the condition is true
        cout << "Pass";

    } else {

        // Display "Fail" if the condition is false
        cout << "Fail";
    }

    // End the program successfully
    return 0;
}